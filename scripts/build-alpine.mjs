// Rebuild after editing the Alpine scene, renderer, or controller:
// node scripts/build-alpine.mjs
// A committed classic-script bundle lets index.html animate from file:// as well
// as HTTP. No build tool, server, or dependency is required to view the page.
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const read = (path) => readFile(new URL(path, root), 'utf8');
const replace = (source, before, after) => {
  if (!source.includes(before)) throw new Error(`Bundle source changed: ${before}`);
  return source.replace(before, after);
};
let scene = await read('assets/vendor/ascii-rest/alpine-dawn.js');
scene = replace(scene, 'export const meta', 'const meta');
scene = replace(scene, 'export default function alpineDawn', 'function alpineDawn');
let renderer = await read('assets/js/alpine-renderer.js');
renderer = replace(renderer, 'export function createRenderer', 'function createRenderer');
let controller = await read('assets/js/alpine-background.js');
controller = replace(controller, "import { createRenderer } from './alpine-renderer.js';", '');
controller = replace(controller, "import { meta } from '../vendor/ascii-rest/alpine-dawn.js';", '');
controller = replace(controller, "const scene = await import('../vendor/ascii-rest/alpine-dawn.js');", 'const scene = { default: alpineDawn };');
controller = replace(controller, "new URL('./alpine-worker.js', import.meta.url)", "new URL('./alpine-worker.js', scriptUrl)");
const bundle = `// Generated by scripts/build-alpine.mjs. Edit its source files, then rebuild.\n// Alpine Dawn by @bas3line, MIT; see ../vendor/ascii-rest/LICENSE.\n(() => {\n'use strict';\nconst scriptUrl = document.currentScript.src;\n${scene}\n${renderer}\n${controller}\n})();\n`;
await writeFile(new URL('assets/js/alpine-background.bundle.js', root), bundle);
console.log(`Built Alpine background (${Buffer.byteLength(bundle)} bytes).`);
